    try {
      const res = await fetch(`https://api.open-meteo.com/v1/forecast?latitude=${city.lat}&longitude=${city.lon}&current=temperature_2m,precipitation&daily=temperature_2m_max,temperature_2m_min,precipitation_sum&timezone=auto&forecast_days=7`);
      if (!res.ok) throw new Error("weather");
      weather.forecast = await res.json();
      weather.cached = false;
      weather.fail = false;
      localStorage.setItem(key, JSON.stringify(weather.forecast));
    } catch {
      const cached = localStorage.getItem(key);
      weather.forecast = cached ? JSON.parse(cached) : null;
      weather.cached = Boolean(cached);
      weather.fail = !cached;
    }
