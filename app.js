function rankDiseases(speciesId, selected) {
  const set = new Set(selected);
  return DATA.diseases.map((disease) => {
    if (!disease.species.includes(speciesId)) return null;
    const hits = disease.symptomIds.filter((id) => set.has(id));
    if (!hits.length) return null;
    const keyHits = disease.keyIds.filter((id) => set.has(id));
    let score = hits.length / disease.symptomIds.length;
    if (disease.keyIds.length && !keyHits.length) score = Math.min(score, 0.34);
    if (keyHits.length) score = Math.min(1, score + 0.12 * keyHits.length);
    const extras = selected.filter((id) => !disease.symptomIds.includes(id)).length;
    score = Math.max(0, score - extras * 0.04);
    return { disease, score };
  }).filter((row) => row && row.score >= 0.2).sort((a, b) => b.score - a.score).slice(0, 4);
}

function readComplaint(query) {
  const q = query.toLowerCase().trim();
  if (q.length < 2) return [];
  const tokens = q.replace(/[^\p{L}\p{N}\s]/gu, " ").split(/\s+/).filter((part) => part.length > 2);
  return DATA.diseases.map((disease) => {
    const hay = [disease.en, disease.ur, disease.summaryEn, disease.summaryUr, ...disease.aka, ...disease.reads].join("\n").toLowerCase();
    let score = 0;
    for (const phrase of disease.reads) {
      const p = phrase.toLowerCase();
      if (p.length >= 4 && q.includes(p)) score += 5;
    }
    for (const token of tokens) if (hay.includes(token)) score += 1;
    return { disease, score };
  }).filter((row) => row.score >= 2).sort((a, b) => b.score - a.score).slice(0, 5);
}

function fertilizer(crop, area, unitToAcre) {
  const acres = Math.max(0, area) * unitToAcre;
  const dap = (crop.p * acres) / 23;
  const urea = Math.max(0, crop.n * acres - dap * 9) / 23;
  const sop = (crop.k * acres) / 25;
  const mop = (crop.k * acres) / 30;
  return { dap, urea, sop, mop };
}
function doseMl(weight, mgPerKg, mgPerMl) {
  if (weight <= 0 || mgPerKg <= 0 || mgPerMl <= 0) return 0;
  return (weight * mgPerKg) / mgPerMl;
}
function cattleKg(girth, length) {
  const g = girth / 2.54; const l = length / 2.54;
  return ((g * g * l) / 300) * 0.453592;
}
function goatKg(girth, length) { return (girth * girth * length) / 10450; }

