function wordsToNumber(tokens) {
  if (!tokens.length) return null;
  if (tokens.length === 1 && /^\d+(\.\d+)?$/.test(tokens[0])) return Number(tokens[0]);
  let total = 0, current = 0, seen = false;
  for (const raw of tokens) {
    if (SAU.has(raw)) { seen = true; current = (current || 1) * 100; continue; }
    if (raw in ONES) { seen = true; current += ONES[raw]; continue; }
    return null;
  }
  return seen ? total + current : null;
}
function parseLine(text) {
  const tokens = text.toLowerCase().replace(/[.,،!?؟]/g, " ").split(/\s+/).filter(Boolean);
  const speciesId = SPECIES_KEYS.find(([, keys]) => tokens.some((token) => keys.includes(token)))?.[0];
  let tag, weightKg;
  const tagAt = tokens.findIndex((token) => ["number","no","tag","num"].includes(token));
  if (tagAt >= 0) tag = wordsToNumber(tokens.slice(tagAt + 1, tagAt + 3))?.toString();
  const kilo = tokens.lastIndexOf("kilo") >= 0 ? tokens.lastIndexOf("kilo") : tokens.lastIndexOf("kg");
  if (kilo > 0) weightKg = wordsToNumber(tokens.slice(Math.max(0, kilo - 4), kilo));
  return { speciesId, tag, weightKg, low: !(speciesId && tag && weightKg) };
}

