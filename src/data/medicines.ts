export function medicineById(id: string) {
  return MEDICINES.find((item) => item.id === id);
}

function fold(value: string) {
  return value.toLowerCase().replace(/[^\p{L}\p{N}]+/gu, " ").replace(/\s+/g, " ").trim();
}

export function searchMedicines(query: string): Medicine[] {
  const q = fold(query);
  if (q.length < 2) return [];
  const tokens = q.split(" ").filter((token) => token.length > 2);
  return MEDICINES.map((medicine) => {
    const names = [medicine.en, medicine.ur, ...medicine.aliases].map(fold);
    let score = 0;
    if (names.some((name) => name === q || name.includes(q))) score += 8;
    for (const token of tokens) {
      if (names.some((name) => name.includes(token))) score += 2;
    }
    return { medicine, score };
  })
    .filter((row) => row.score >= 2)
    .sort((a, b) => b.score - a.score)
    .map((row) => row.medicine);
}
